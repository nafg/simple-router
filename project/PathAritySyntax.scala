import sbt.*

/** Generates `PathAritySyntax.scala`: the `>>` and `construct` syntax for each number of path parameters from 1 to
  * [[MaxArity]], which would otherwise be written out by hand once per arity
  */
object PathAritySyntax {
  val MaxArity = 22

  def generate(sourceManaged: File): Seq[File] = {
    val file = sourceManaged / "simplerouter" / "PathAritySyntax.scala"
    IO.write(file, source)
    Seq(file)
  }

  private def source: String = {
    def classes(n: Int) = {
      val ts     = (1 to n).map(i => s"T$i")
      val vs     = (1 to n).map(i => s"t$i")
      val tuple  = ts.mkString("", " ->: ", " ->: Unit")
      val tparms = ts.mkString(", ")
      s"""
         |  /** `>>` for a path with $n parameters */
         |  implicit class Path${n}HandlerSyntax[$tparms](self: From[$tuple]) extends PathNHandlerSyntax[$tuple](self) {
         |    override type F[Z] = ${ts.mkString("", " => ", " => Z")}
         |    override protected def uncurry[Z](f: F[Z]) = { case ${vs.mkString("", " ->: ", " ->: ()")} =>
         |      f${vs.map(v => s"($v)").mkString}
         |    }
         |  }
         |
         |  /** `construct` for a path with $n parameters */
         |  implicit class Path${n}BuildSyntax[$tparms](self: From[$tuple]) {
         |
         |    /** The [[Location]] the path describes for these parameters, in order: [[Path.build]] of their tuple */
         |    def construct(${vs.zip(ts).map { case (v, t) => s"$v: $t" }.mkString(", ")}) =
         |      toPath(self).build(${vs.mkString("", " ->: ", " ->: ()")})
         |  }
         |""".stripMargin
    }

    s"""// Generated by project/PathAritySyntax.scala
       |package simplerouter
       |
       |import simplerouter.Tuples.{->:, Any_->:}
       |
       |/** `>>`, whose handler takes a path's parameters as separate, curried arguments, and `construct`, which builds a
       |  * [[Location]] from them, for paths with 1 to $MaxArity parameters
       |  */
       |trait PathAritySyntax extends ImplicitsForToPath[λ[a => a]] {
       |${(1 to MaxArity).map(classes).mkString}}
       |""".stripMargin
  }
}
